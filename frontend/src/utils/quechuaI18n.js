export function translateAlertText(alert, lang = "es") {
  const cleanTitleEs = (alert?.title_es || "").replace(/\s*\([^)]*\)/g, "").replace(/[¡!]/g, "").trim();
  if (lang !== "qu") {
    return {
      title: cleanTitleEs,
      category: alert?.category || "Campo",
      action: alert?.action_es || "",
    };
  }
  const qu = ALERT_QU_MAP[alert?.id];
  return {
    title: qu?.title || cleanTitleEs,
    category: qu?.cat || "Chakra",
    action: qu?.action || alert?.action_qu || alert?.action_es || "",
  };
}

